static int CompareEntry(const void* key, const void* elem) {
  const StdHeaderEntry* entry = elem;
  return strcmp((const char*)key, entry->symbol);
}

static const StdHeaderEntry* FindEntry(const char* symbol) {
  if (symbol == NULL || symbol[0] == '\0') {
    return NULL;
  }
  return bsearch(symbol, kStdHeaders,
                 sizeof(kStdHeaders) / sizeof(kStdHeaders[0]),
                 sizeof(kStdHeaders[0]), CompareEntry);
}

static const char* HeaderForEntry(const StdHeaderEntry* entry) {
  if (entry == NULL) {
    return NULL;
  }
  if (CompilerIsCXX()) {
    return entry->cxx_header != NULL ? entry->cxx_header : entry->c_header;
  }
  return entry->c_header;
}

static bool QualifiedNameIsStd(const char* spelling) {
  if (spelling == NULL) {
    return false;
  }
  if (strncmp(spelling, "std::", 5) == 0) {
    return true;
  }
  if (strncmp(spelling, "::std::", 7) == 0) {
    return true;
  }
  return false;
}

static bool IdentifierLooksLikeStdUse(FullyQualifiedIdentifier* name) {
  if (name == NULL || name->components.length == 0) {
    return false;
  }
  if (!name->is_qualified && name->components.length == 1) {
    return true;
  }
  String* first = name->components.value.p[0];
  return first != NULL && strcmp(first->value, "std") == 0;
}

static const char* LeafFromSpelling(const char* spelling) {
  if (spelling == NULL) {
    return NULL;
  }
  const char* last = strrchr(spelling, ':');
  if (last != NULL && last > spelling && last[-1] == ':') {
    return last + 1;
  }
  return spelling;
}

static void EmitHeaderNote(Syntax* syntax, const char* shown,
                           const StdHeaderEntry* entry) {
  if (syntax == NULL || entry == NULL ||
      DiagnosticErrorTrapped() || DiagnosticsSuppressed()) {
    return;
  }
  const char* header = HeaderForEntry(entry);
  if (header == NULL) {
    return;
  }
  if (shown == NULL || shown[0] == '\0') {
    shown = entry->symbol;
  }
  const char* filename = NULL;
  int lineno = 0;
  if (syntax->lex != NULL && syntax->lex->source != NULL) {
    filename = syntax->lex->source->filename.value;
    lineno = syntax->lex->source->lineno;
  }
  if (CompilerIsCXX() && CompilerCXXAtLeast(kLanguageStandardCXX20) &&
      entry->cxx_header != NULL) {
    ReportNote(filename, lineno,
               "'%s' is defined in header <%s>; did you forget to "
               "'#include <%s>' or 'import std;'?",
               shown, header, header);
  } else {
    ReportNote(filename, lineno,
               "'%s' is defined in header <%s>; did you forget to "
               "'#include <%s>'?",
               shown, header, header);
  }
}

void ReportStdHeaderSuggestion(Syntax* syntax,
                               FullyQualifiedIdentifier* name) {
  if (syntax == NULL || name == NULL || !IdentifierLooksLikeStdUse(name)) {
    return;
  }
  const char* leaf = FullyQualifiedIdentifierLast(name);
  const StdHeaderEntry* entry = FindEntry(leaf);
  if (entry == NULL) {
    return;
  }
  const char* shown = name->spelling.value;
  if (shown == NULL || shown[0] == '\0') {
    shown = leaf;
  }
  EmitHeaderNote(syntax, shown, entry);
}

void ReportStdHeaderSuggestionForName(Syntax* syntax, const char* spelling) {
  if (syntax == NULL || spelling == NULL || spelling[0] == '\0') {
    return;
  }
  const char* leaf = LeafFromSpelling(spelling);
  if (leaf != spelling && !QualifiedNameIsStd(spelling)) {
    return;
  }
  const StdHeaderEntry* entry = FindEntry(leaf);
  if (entry == NULL) {
    return;
  }
  EmitHeaderNote(syntax, spelling, entry);
}
