def rows(art):
    return [line.strip() for line in art.strip().splitlines()]


def encode(pixels):
    out = []
    for i in range(0, len(pixels), 4):
        value = 0
        for p, ch in enumerate(pixels[i : i + 4]):
            c = COLOUR[ch]
            value |= ((c >> 1) & 1) << (7 - p)
            value |= (c & 1) << (3 - p)
        out.append(value)
    return out


def column_major(byte_rows):
    return [byte_rows[r][c] for c in range(len(byte_rows[0])) for r in range(len(byte_rows))]


def cell(art):
    return column_major([encode(r) for r in rows(art)])


def cell16(art):
    """16x16 art as two character-row windows (32 + 32 bytes)."""
    r = rows(art)
    top = column_major([encode(line) for line in r[:8]])
    bot = column_major([encode(line) for line in r[8:16]])
    return top + bot


def window(art, shift):
    padded = ["...." + "." * shift + r + "." * (4 - shift) for r in rows(art)]
    return column_major([encode(r) for r in padded])


def pair(art):
    return window(art, 0) + window(art, 2)


def soft16(art, shift):
    """16x16 rock as 6x16 column-major strips (blank | art | blank), 2px shift."""
    out = []
    for r in rows(art):
        line = "...." + ("." * shift) + r + ("." * (4 - shift))
        if len(line) != 24:
            raise ValueError("soft16 width %d" % len(line))
        out.append(line)
    return column_major([encode(line) for line in out])


def soft16_pair(art):
    return soft16(art, 0) + soft16(art, 2)


def soft8(art, shift):
    """8x8 rock as 4x8 column-major strips with side blanks and 2px shift."""
    out = ["...." + ("." * shift) + r + ("." * (4 - shift)) for r in rows(art)]
    return column_major([encode(line) for line in out])


def soft8_pair(art):
    return soft8(art, 0) + soft8(art, 2)


def strip(art):
    return [0, 0] + [encode(r)[0] for r in rows(art)]


def glyph(hex_rows, ink="W"):
    bits = [int(h, 16) for h in hex_rows.split()]
    art = "\n".join(
        "".join(ink if b & (0x80 >> p) else "." for p in range(8)) for b in bits
    )
    return cell(art)


def encode2(pixels):
    """BBC Mode 2: 2 pixels per byte (16 colours, using steady 0..7)."""
    out = []
    for i in range(0, len(pixels), 2):
        value = 0
        for p, ch in enumerate(pixels[i : i + 2]):
            c = COLOUR2[ch]
            value |= ((c >> 3) & 1) << (7 - p)
            value |= ((c >> 2) & 1) << (5 - p)
            value |= ((c >> 1) & 1) << (3 - p)
            value |= (c & 1) << (1 - p)
        out.append(value)
    return out


def cell2(art):
    """Mode-2 column-major strips (e.g. 8x12 -> 4 strips of 12 scanlines = 48 bytes)."""
    return column_major([encode2(r) for r in rows(art)])


def glyph2(hex_rows, ink="W"):
    """Mode-2 8x8 HUD digit (4 byte-cols x 8 scanlines = 32 bytes)."""
    bits = [int(h, 16) for h in hex_rows.split()]
    art = "\n".join(
        "".join(ink if b & (0x80 >> p) else "." for p in range(8)) for b in bits
    )
    return cell2(art)


def pm_wall_tile(mask):
    """Neighbor-connected hollow blue Mode-2 wall tile (mask bits: 1=N, 2=E, 4=S, 8=W)."""
    N = bool(mask & 1)
    E = bool(mask & 2)
    S = bool(mask & 4)
    W = bool(mask & 8)

    def in_r(x, y):
        if y < 0:
            return N and (1 <= x <= 6)
        if y > 11:
            return S and (1 <= x <= 6)
        if x < 0:
            return W and (2 <= y <= 9)
        if x > 7:
            return E and (2 <= y <= 9)
        if 1 <= x <= 6 and 2 <= y <= 9:
            return True
        if N and 1 <= x <= 6 and y < 2:
            return True
        if S and 1 <= x <= 6 and y > 9:
            return True
        if W and 2 <= y <= 9 and x < 1:
            return True
        if E and 2 <= y <= 9 and x > 6:
            return True
        return False

    lines = []
    for y in range(12):
        row = []
        for x in range(8):
            if not in_r(x, y):
                row.append(".")
            else:
                interior = all(
                    in_r(x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1)
                )
                row.append("." if interior else "B")
        lines.append("".join(row))
    return cell2("\n".join(lines))


def emit(name, data, per_line=8):
    # One section per bitmap so --gc-sections can drop Invaders/Snake art
    # from ASTERO (shared sprites.o was blowing the DFS HIMEM load budget).
    print('.section ".text.blitter.%s", "ax", @progbits' % name)
    print(".global %s" % name)
    print("%s:" % name)
    for i in range(0, len(data), per_line):
        print("  .byte " + ", ".join("0x%02x" % b for b in data[i : i + per_line]))
    print()


