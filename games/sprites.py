# The Master's 8x8 digits, a row per byte (bit 7 left), so the HUD digits
# drawn from here match the OS text beside them.
DIGITS = (
    "3C 66 6E 7E 76 66 3C 00",
    "18 38 18 18 18 18 7E 00",
    "3C 66 06 0C 18 30 7E 00",
    "3C 66 06 1C 06 66 3C 00",
    "0C 1C 3C 6C 7E 0C 0C 00",
    "7E 60 7C 06 06 66 3C 00",
    "1C 30 60 7C 66 66 3C 00",
    "7E 06 0C 18 30 30 30 00",
    "3C 66 66 3C 66 66 3C 00",
    "3C 66 66 3E 06 0C 38 00",
)

COLOUR = {".": 0, "G": 1, "R": 2, "W": 3}


def rows(art):
    return [line.strip() for line in art.strip().splitlines()]


def encode(pixels):
    out = []
    for i in range(0, len(pixels), 4):
        value = 0
        for p, ch in enumerate(pixels[i : i + 4]):
            c = COLOUR[ch]
            value |= ((c >> 1) & 1) << (7 - p)
            value |= (c & 1) << (3 - p)
        out.append(value)
    return out


def column_major(byte_rows):
    return [byte_rows[r][c] for c in range(len(byte_rows[0])) for r in range(len(byte_rows))]


def cell(art):
    return column_major([encode(r) for r in rows(art)])


def cell16(art):
    """16x16 art as two character-row windows (32 + 32 bytes)."""
    r = rows(art)
    top = column_major([encode(line) for line in r[:8]])
    bot = column_major([encode(line) for line in r[8:16]])
    return top + bot


def window(art, shift):
    padded = ["...." + "." * shift + r + "." * (4 - shift) for r in rows(art)]
    return column_major([encode(r) for r in padded])


def pair(art):
    return window(art, 0) + window(art, 2)


def soft16(art, shift):
    """16x16 rock as 6x16 column-major strips (blank | art | blank), 2px shift."""
    out = []
    for r in rows(art):
        line = "...." + ("." * shift) + r + ("." * (4 - shift))
        if len(line) != 24:
            raise ValueError("soft16 width %d" % len(line))
        out.append(line)
    return column_major([encode(line) for line in out])


def soft16_pair(art):
    return soft16(art, 0) + soft16(art, 2)


def soft8(art, shift):
    """8x8 rock as 4x8 column-major strips with side blanks and 2px shift."""
    out = ["...." + ("." * shift) + r + ("." * (4 - shift)) for r in rows(art)]
    return column_major([encode(line) for line in out])


def soft8_pair(art):
    return soft8(art, 0) + soft8(art, 2)


def strip(art):
    return [0, 0] + [encode(r)[0] for r in rows(art)]


def glyph(hex_rows, ink="W"):
    bits = [int(h, 16) for h in hex_rows.split()]
    art = "\n".join(
        "".join(ink if b & (0x80 >> p) else "." for p in range(8)) for b in bits
    )
    return cell(art)


def emit(name, data, per_line=8):
    # One section per bitmap so --gc-sections can drop Invaders/Snake art
    # from ASTERO (shared sprites.o was blowing the DFS HIMEM load budget).
    print('.section ".text.blitter.%s", "ax", @progbits' % name)
    print(".global %s" % name)
    print("%s:" % name)
    for i in range(0, len(data), per_line):
        print("  .byte " + ", ".join("0x%02x" % b for b in data[i : i + per_line]))
    print()


def main():
    print("// Generated by games/sprites.py; edit the art there and rerun it.")
    print("// Parked in .text.blitter.* with the screen helpers so they stay below")
    print("// &3000, where they can be read while the shadow screen is mapped.")
    print()
    for name, frames in (("squid", SQUID), ("crab", CRAB), ("oct", OCTOPUS)):
        for frame, art in enumerate(frames):
            emit("k_%s%d" % (name, frame), window(art, 0))
    emit("k_cannon", pair(CANNON))
    emit("k_cannon_red", pair(CANNON.replace("G", "R")))
    emit("k_blast", pair(BOOM))
    emit("k_ufo", pair(UFO))
    emit("k_boom", cell(BOOM))
    bunker = rows(BUNKER)
    emit("k_bunker_top", column_major([encode(r) for r in bunker[:8]]))
    emit("k_bunker_base", column_major([encode(r) for r in bunker[8:]]))
    for frame, art in enumerate(BOMBS):
        emit("k_bomb%d" % frame, strip(art), per_line=10)
    emit("k_digits", [b for d in DIGITS for b in glyph(d)])
    # Snake board cells — one character cell (16 bytes) each.
    emit("k_sn_head_u", cell(SN_HEAD_U))
    emit("k_sn_head_d", cell(SN_HEAD_D))
    emit("k_sn_head_l", cell(SN_HEAD_L))
    emit("k_sn_head_r", cell(SN_HEAD_R))
    emit("k_sn_body", cell(SN_BODY))
    emit("k_sn_tail", cell(SN_TAIL))
    emit("k_sn_apple0", cell(SN_APPLE0))
    emit("k_sn_apple1", cell(SN_APPLE1))
    emit("k_sn_bonus0", cell(SN_BONUS0))
    emit("k_sn_bonus1", cell(SN_BONUS1))
    emit("k_sn_rock", cell(SN_ROCK))
    emit("k_sn_wall", cell(SN_WALL))
    # Ship is 4x16 column-major (cell over 16 rows) so rock_blit can
    # wipe+draw it in one shadow pass, like the rocks. Same 64 bytes
    # per heading as the old cell16 layout, just column-ordered.
    for i, art in enumerate(AS_SHIP):
        emit("k_as_ship%d" % i, cell(art))
    for i, art in enumerate(AS_SHIP_THRUST):
        emit("k_as_ship_t%d" % i, cell(art))
    # Each rock is a pair: shift 0 then shift 2 px, so X moves in 2 px
    # steps (byte column + phase) instead of 4 px jumps.
    emit("k_as_rock_l0", soft16_pair(AS_ROCK_L0))
    emit("k_as_rock_l1", soft16_pair(AS_ROCK_L1))
    emit("k_as_rock_m0", soft8_pair(AS_ROCK_M0))
    emit("k_as_rock_m1", soft8_pair(AS_ROCK_M1))
    emit("k_as_rock_s0", soft8_pair(AS_ROCK_S0))
    emit("k_as_rock_s1", soft8_pair(AS_ROCK_S1))
    for i, art in enumerate(AS_SHOT_PHASES):
        emit("k_as_shot%d" % i, [encode(r)[0] for r in rows(art)], per_line=3)
    emit("k_as_boom0", cell(AS_BOOM0))
    emit("k_as_boom1", cell(AS_BOOM1))


if __name__ == "__main__":
    main()
